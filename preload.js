const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('agua', {
  drink: () => ipcRenderer.send('drink'),
  snooze: () => ipcRenderer.send('snooze'),
  pontoDone: () => ipcRenderer.send('ponto:done'),
  pontoSnooze: () => ipcRenderer.send('ponto:snooze'),
  testAlert: () => ipcRenderer.send('alert:test'),
  closeAlert: () => ipcRenderer.send('alert:close'),
  eventSnooze: () => ipcRenderer.send('event:snooze'),
  getPlan: () => ipcRenderer.invoke('plan:get'),
  addEvent: e => ipcRenderer.invoke('plan:addEvent', e),
  delEvent: id => ipcRenderer.invoke('plan:delEvent', id),
  addTask: t => ipcRenderer.invoke('plan:addTask', t),
  toggleTask: id => ipcRenderer.invoke('plan:toggleTask', id),
  delTask: id => ipcRenderer.invoke('plan:delTask', id),
  getConfig: () => ipcRenderer.invoke('config:get'),
  saveConfig: cfg => ipcRenderer.invoke('config:save', cfg),
  getReport: () => ipcRenderer.invoke('report:get'),
  pickSound: () => ipcRenderer.invoke('sound:pick'),
  clearSound: () => ipcRenderer.invoke('sound:clear'),
  setLang: lang => ipcRenderer.invoke('lang:set', lang),
  setTheme: theme => ipcRenderer.invoke('theme:set', theme),
  weatherSearch: name => ipcRenderer.invoke('weather:search', name),
  weatherDetect: () => ipcRenderer.invoke('weather:detect'),
  weatherGet: () => ipcRenderer.invoke('weather:get'),
  weatherSet: w => ipcRenderer.invoke('weather:set', w),
  getTime: () => ipcRenderer.invoke('time:get'),
  checkIn: () => ipcRenderer.invoke('time:checkin'),
  checkOut: note => ipcRenderer.invoke('time:checkout', note),
  addTime: entry => ipcRenderer.invoke('time:add', entry),
  deleteTime: id => ipcRenderer.invoke('time:delete', id),
  exportTime: (year, month) => ipcRenderer.invoke('time:export', { year, month }),
  onTimeChanged: cb => ipcRenderer.on('time:changed', () => cb())
});
